// Builds the account service (accounts/src) into one file, accounts/accounts-worker.js,
// which the owner pastes into the Cloudflare dashboard. Run: npm run build:accounts
import { build } from 'esbuild';

await build({
  entryPoints: ['accounts/src/worker.ts'],
  outfile: 'accounts/accounts-worker.js',
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'es2022',
  mainFields: ['module', 'main'],
  conditions: ['worker', 'browser', 'import'],
  minify: true,
  legalComments: 'inline',
  banner: {
    js: '// Ancient Pathfinder accounts service. Generated by `npm run build:accounts` from accounts/src; do not edit by hand.\n// Paste this whole file into the Cloudflare Worker editor (see accounts/README.md).',
  },
});
console.log('wrote accounts/accounts-worker.js');
