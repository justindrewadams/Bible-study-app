// Generates relay/esv-relay.js: a Cloudflare Worker that fetches ESV text from Crossway's
// official API using a key stored as a Cloudflare secret, so the key is never in this
// repository or in the published website. Book names and verse counts are embedded so the
// relay can enforce Crossway's per-page limits itself. Run: npm run build:relay
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const counts = JSON.parse(fs.readFileSync(path.join(root, 'src', 'data', 'verseCounts.json'), 'utf8'));
const booksTs = fs.readFileSync(path.join(root, 'src', 'data', 'books.ts'), 'utf8');
const books = {};
for (const m of booksTs.matchAll(/\['([1-3]?[A-Za-z]+)', '([^']+)', (\d+)\]/g)) {
  const [, osis, name, chapters] = m;
  if (counts[osis]?.length !== Number(chapters)) throw new Error(`verse counts missing for ${osis}`);
  books[osis] = [name, counts[osis]];
}
if (Object.keys(books).length !== 66) throw new Error('expected 66 books');

// API.Bible names books with USFM codes ("GEN", "JHN"), in the same order as the app's books
const USFM = ('GEN EXO LEV NUM DEU JOS JDG RUT 1SA 2SA 1KI 2KI 1CH 2CH EZR NEH EST JOB PSA PRO ECC SNG ISA JER LAM ' +
  'EZK DAN HOS JOL AMO OBA JON MIC NAM HAB ZEP HAG ZEC MAL MAT MRK LUK JHN ACT ROM 1CO 2CO GAL EPH PHP COL 1TH 2TH ' +
  '1TI 2TI TIT PHM HEB JAS 1PE 2PE 1JN 2JN 3JN JUD REV').split(' ');
Object.keys(books).forEach((osis, i) => books[osis].push(USFM[i]));
for (const [osis, code] of [['Gen', 'GEN'], ['Ps', 'PSA'], ['Song', 'SNG'], ['John', 'JHN'], ['Rev', 'REV']]) {
  if (books[osis]?.[2] !== code) throw new Error(`book order mismatch at ${osis}`);
}

const src = `// Ancient Pathfinder relay: a Cloudflare Worker (generated by scripts/build-relay.mjs; do not edit by hand).
// It serves the ESV (Crossway's ESV API) and the NASB 1995, CSB and NKJV (API.Bible's free Starter plan).
//
// ESV: the app asks this relay for a passage; the relay adds the ESV API key, which is kept as a
// Cloudflare secret named ESV_API_KEY, and asks Crossway's official ESV API. The key is never
// sent to browsers, stored in the repository or published with the website.
//
// It keeps to Crossway's free, non-commercial ESV API terms (https://api.esv.org/):
//  - at most 500 verses, and at most half of a book, per request (one screen in the app)
//  - /verses (for the app's verse search) returns at most 6 single verses per request
//  - ESV text is never cached by the relay ("Cache-Control: no-store")
//  - only requests from the app's own site are answered (ALLOWED_ORIGINS)
//
// Settings (Cloudflare dashboard → the Worker → Settings → Variables and Secrets):
//   ESV_API_KEY      secret, required: the token from api.esv.org
//   ALLOWED_ORIGINS  text, optional:   comma-separated sites allowed to use the relay
//                                      (default: the ancientpathfinder.com addresses and justindrewadams.github.io)
//
// API.Bible (/abible): NASB 1995, CSB and NKJV under the free, non-commercial Starter plan
// (https://api.bible/terms-and-conditions):
//  - whole chapters are kept in a Cloudflare KV store so each chapter is fetched from API.Bible
//    at most once every 25 days, however many people read it. Their terms require cached text to be
//    refreshed at least every 30 days: a chapter is refetched after 25 days, never served once it is
//    30 days old, and KV deletes it by itself at 30 days.
//  - every call to API.Bible is counted, and the relay stops calling once 4,500 calls were made in
//    the last 31 days (the plan allows 5,000 a month). Stored chapters keep working; others show the
//    WEB in the app until the count drops.
//  - chapters are only fetched when someone reads them (no copying whole Bibles in advance)
//  - each chapter keeps API.Bible's usage-tracking (FUMS) token, which the app reports on every view
//   API_BIBLE_KEY    secret, required for /abible: the key from api.bible
//   ABIBLE_STORE     KV namespace binding, required for /abible (Settings → Bindings → KV namespace)
//   API_BIBLE_OFF    text, optional: "ALL", or translations to stop serving, e.g. "NKJV"
//   API_BIBLE_IDS    text, optional: API.Bible's Bible ids, e.g. "NASB1995=xxxx,CSB=yyyy,NKJV=zzzz"
//                    (normally looked up automatically)
//   API_BIBLE_MONTHLY_CAP  text, optional: the call limit per 31 days (default 4500)

const BOOKS = ${JSON.stringify(books)};

const DEFAULT_ORIGINS = 'https://ancientpathfinder.com,https://www.ancientpathfinder.com,https://justindrewadams.github.io';
const MAX_VERSES = 500;
const MAX_SEARCH_VERSES = 6;

/** "Rom.3.23" -> "Romans 3:23", or null if it isn't a real verse. */
function verseRef(osis) {
  const m = /^([1-3]?[A-Za-z]+)\\.(\\d+)\\.(\\d+)$/.exec(osis);
  const book = m && BOOKS[m[1]];
  if (!book) return null;
  const chapter = Number(m[2]);
  const verse = Number(m[3]);
  if (chapter < 1 || chapter > book[1].length || verse < 1 || verse > book[1][chapter - 1]) return null;
  return book[0] + ' ' + chapter + ':' + verse;
}

/** Asks Crossway for the text of q, with the app's fixed formatting. */
async function esvText(q, env, numbers) {
  const params = new URLSearchParams({
    q,
    'include-headings': 'false',
    'include-footnotes': 'false',
    'include-verse-numbers': numbers ? 'true' : 'false',
    'include-first-verse-numbers': numbers ? 'true' : 'false',
    'include-short-copyright': 'false',
    'include-copyright': 'false',
    'include-passage-references': 'false',
  });
  return fetch('https://api.esv.org/v3/passage/text/?' + params, { headers: { Authorization: 'Token ' + env.ESV_API_KEY } });
}

function esvError(res, origin) {
  if (res.status === 429) return reply({ error: 'The ESV service limit was reached. Please try again later.' }, 429, origin);
  if (res.status === 401 || res.status === 403) return reply({ error: 'The relay\\'s ESV key was not accepted.' }, 502, origin);
  return reply({ error: 'The ESV service returned ' + res.status + '.' }, 502, origin);
}

// --- API.Bible ---------------------------------------------------------------------------

const ABIBLE_BASE = 'https://rest.api.bible/v1';
/** the app's code -> abbreviations API.Bible may list it under */
const ABIBLE_VERSIONS = { NASB1995: ['NASB1995', 'NASB95'], CSB: ['CSB'], NKJV: ['NKJV'] };
const DAY = 86400000;
const REFRESH_AFTER = 25 * DAY;
const MAX_AGE = 30 * DAY;
const DEFAULT_CAP = 4500;
const WINDOW_DAYS = 31;

const norm = (s) => String(s || '').toUpperCase().replace(/[^A-Z0-9]/g, '');

/**
 * Counts one call to API.Bible, or returns false when the last 31 days already used the limit
 * (or the count couldn't be saved, so we can't be sure).
 */
async function spendCall(env) {
  const today = new Date().toISOString().slice(0, 10);
  const since = new Date(Date.now() - (WINDOW_DAYS - 1) * DAY).toISOString().slice(0, 10);
  const usage = (await env.ABIBLE_STORE.get('usage', 'json')) || {};
  for (const d of Object.keys(usage)) if (d < since) delete usage[d];
  const used = Object.values(usage).reduce((a, b) => a + b, 0);
  if (used >= (Number(env.API_BIBLE_MONTHLY_CAP) || DEFAULT_CAP)) return false;
  usage[today] = (usage[today] || 0) + 1;
  try {
    await env.ABIBLE_STORE.put('usage', JSON.stringify(usage), { expirationTtl: (WINDOW_DAYS + 1) * 86400 });
  } catch {
    return false;
  }
  return true;
}

/** API.Bible's id for each of the three Bibles, from the API_BIBLE_IDS setting or looked up (and kept 25 days); null if unreachable. */
async function abibleIds(env) {
  if (env.API_BIBLE_IDS) {
    return Object.fromEntries(env.API_BIBLE_IDS.split(',').map((p) => p.split('=').map((x) => x.trim())).filter((p) => p[1]));
  }
  const saved = await env.ABIBLE_STORE.get('ids', 'json');
  if (saved && Date.now() - saved.at < REFRESH_AFTER && Object.keys(saved.ids).length === 3) return saved.ids;
  if (!(await spendCall(env))) return saved ? saved.ids : null;
  const res = await fetch(ABIBLE_BASE + '/bibles?language=eng', { headers: { 'api-key': env.API_BIBLE_KEY } });
  if (!res.ok) return saved ? saved.ids : null;
  const list = (await res.json()).data || [];
  const ids = {};
  for (const [code, names] of Object.entries(ABIBLE_VERSIONS)) {
    const wanted = names.map(norm);
    const bible = list.find((b) => wanted.includes(norm(b.abbreviation)) || wanted.includes(norm(b.abbreviationLocal)));
    if (bible) ids[code] = bible.id;
  }
  await env.ABIBLE_STORE.put('ids', JSON.stringify({ at: Date.now(), ids }), { expirationTtl: 30 * 86400 }).catch(() => {});
  return ids;
}

/** "[1] In the beginning … [2] The earth …" -> [{ verse: 1, text }, …]; the wording itself is left as it is. */
function abibleVerses(content) {
  const parts = String(content || '').split(/\\[(\\d+)\\]/);
  const verses = [];
  for (let i = 1; i < parts.length; i += 2) {
    const text = (parts[i + 1] || '').replace(/\\s+/g, ' ').trim();
    if (text) verses.push({ verse: Number(parts[i]), text });
  }
  return verses;
}

async function abibleChapter(code, osis, book, chapter, env, origin) {
  const off = norm(env.API_BIBLE_OFF);
  if (off && (off.includes('ALL') || off.includes(norm(code)))) {
    return reply({ error: 'The ' + code + ' is not available right now.' }, 503, origin);
  }
  if (!env.API_BIBLE_KEY || !env.ABIBLE_STORE) return reply({ error: 'The relay is not set up for API.Bible yet.' }, 503, origin);
  const key = 'ch:' + code + ':' + osis + '.' + chapter;
  const saved = await env.ABIBLE_STORE.get(key, 'json');
  const age = saved ? Date.now() - saved.at : Infinity;
  const send = (c) => reply({ verses: c.verses, copyright: c.copyright, fums: c.fums }, 200, origin);
  if (saved && age < REFRESH_AFTER) return send(saved);

  let why = 'The ' + code + ' service limit for this month was reached.';
  if (await spendCall(env)) {
    const ids = await abibleIds(env);
    const id = ids && ids[code];
    if (!ids) why = 'API.Bible could not be reached.';
    else if (!id) why = 'The ' + code + ' is not enabled on this API.Bible account.';
    else {
      const params = new URLSearchParams({
        'content-type': 'text',
        'include-notes': 'false',
        'include-titles': 'false',
        'include-chapter-numbers': 'false',
        'include-verse-numbers': 'true',
        'include-verse-spans': 'false',
      });
      const res = await fetch(ABIBLE_BASE + '/bibles/' + id + '/chapters/' + book[2] + '.' + chapter + '?' + params, {
        headers: { 'api-key': env.API_BIBLE_KEY },
      });
      if (res.ok) {
        const data = await res.json();
        const meta = data.meta || {};
        const fresh = {
          at: Date.now(),
          verses: abibleVerses(data.data && data.data.content),
          copyright: (data.data && data.data.copyright) || '',
          fums: meta.fumsToken || meta.fumsId || '',
        };
        if (fresh.verses.length) {
          // KV deletes it by itself once it is 30 days old
          await env.ABIBLE_STORE.put(key, JSON.stringify(fresh), { expiration: Math.floor((fresh.at + MAX_AGE) / 1000) }).catch(() => {});
          return send(fresh);
        }
        why = 'API.Bible returned no text for this chapter.';
      } else why = 'API.Bible returned ' + res.status + '.';
    }
  }
  // a stored copy may still be shown until it is 30 days old
  if (saved && age < MAX_AGE) return send(saved);
  return reply({ error: why }, 503, origin);
}

function allowedOrigin(request, env) {
  const origin = request.headers.get('Origin') || '';
  const allowed = (env.ALLOWED_ORIGINS || DEFAULT_ORIGINS).split(',').map((s) => s.trim()).filter(Boolean);
  return allowed.includes(origin) ? origin : null;
}

function reply(body, status, origin) {
  return new Response(JSON.stringify(body), {
    status,
    headers: {
      'Content-Type': 'application/json; charset=utf-8',
      'Cache-Control': 'no-store',
      ...(origin ? { 'Access-Control-Allow-Origin': origin, Vary: 'Origin' } : {}),
    },
  });
}

export default {
  async fetch(request, env) {
    const origin = allowedOrigin(request, env);
    if (request.method === 'OPTIONS') {
      return new Response(null, {
        status: origin ? 204 : 403,
        headers: origin
          ? { 'Access-Control-Allow-Origin': origin, 'Access-Control-Allow-Methods': 'GET', 'Access-Control-Max-Age': '86400', Vary: 'Origin' }
          : {},
      });
    }
    if (!origin) return reply({ error: 'This relay only serves the Ancient Pathfinder app.' }, 403, null);
    if (request.method !== 'GET') return reply({ error: 'Only GET is supported.' }, 405, origin);

    const url = new URL(request.url);

    // a whole chapter of the NASB 1995, CSB or NKJV: /abible?bible=CSB&book=John&chapter=3
    if (url.pathname === '/abible') {
      const code = url.searchParams.get('bible') || '';
      const osis = url.searchParams.get('book') || '';
      const book = BOOKS[osis];
      const chapter = Number(url.searchParams.get('chapter'));
      if (!Object.prototype.hasOwnProperty.call(ABIBLE_VERSIONS, code)) return reply({ error: 'Unknown translation.' }, 400, origin);
      if (!book || !Number.isInteger(chapter) || chapter < 1 || chapter > book[1].length) {
        return reply({ error: 'Unknown book or chapter.' }, 400, origin);
      }
      return abibleChapter(code, osis, book, chapter, env, origin);
    }

    if (!env.ESV_API_KEY) return reply({ error: 'The relay has no ESV_API_KEY secret yet.' }, 503, origin);

    // a few single verses at once, for the app's verse search: /verses?refs=Rom.3.23,Ps.23.1
    if (url.pathname === '/verses') {
      const refs = (url.searchParams.get('refs') || '').split(',').filter(Boolean);
      if (!refs.length || refs.length > MAX_SEARCH_VERSES) {
        return reply({ error: 'Ask for 1 to ' + MAX_SEARCH_VERSES + ' verses.' }, 400, origin);
      }
      const names = refs.map(verseRef);
      if (names.some((n) => !n)) return reply({ error: 'Unknown verse.' }, 400, origin);
      const res = await esvText(names.join('; '), env, false);
      if (!res.ok) return esvError(res, origin);
      const data = await res.json();
      return reply({
        passages: data.passages || [],
        canonical: (data.passage_meta || []).map((m) => m.canonical),
      }, 200, origin);
    }

    if (url.pathname !== '/passage') return reply({ error: 'Not found.' }, 404, origin);
    const book = BOOKS[url.searchParams.get('book') || ''];
    const chapter = Number(url.searchParams.get('chapter'));
    const from = Number(url.searchParams.get('from'));
    const to = Number(url.searchParams.get('to'));
    if (!book || !Number.isInteger(chapter) || chapter < 1 || chapter > book[1].length) {
      return reply({ error: 'Unknown book or chapter.' }, 400, origin);
    }
    const inChapter = book[1][chapter - 1];
    const bookTotal = book[1].reduce((a, b) => a + b, 0);
    if (!Number.isInteger(from) || !Number.isInteger(to) || from < 1 || to < from || to > inChapter) {
      return reply({ error: 'Invalid verse range.' }, 400, origin);
    }
    const limit = Math.max(1, Math.min(MAX_VERSES, Math.floor(bookTotal / 2)));
    if (to - from + 1 > limit) {
      return reply({ error: 'That is more than Crossway allows on one page (' + limit + ' verses).' }, 400, origin);
    }

    const res = await esvText(book[0] + ' ' + chapter + ':' + from + '-' + to, env, true);
    if (!res.ok) return esvError(res, origin);
    const data = await res.json();
    return reply({ passages: data.passages || [] }, 200, origin);
  },
};
`;
fs.mkdirSync(path.join(root, 'relay'), { recursive: true });
fs.writeFileSync(path.join(root, 'relay', 'esv-relay.js'), src);
console.log(`relay/esv-relay.js written (${(src.length / 1024).toFixed(1)} KB)`);
