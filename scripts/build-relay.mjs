// Generates relay/esv-relay.js: a Cloudflare Worker that fetches ESV text from Crossway's
// official API using a key stored as a Cloudflare secret, so the key is never in this
// repository or in the published website. Book names and verse counts are embedded so the
// relay can enforce Crossway's per-page limits itself. Run: npm run build:relay
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const counts = JSON.parse(fs.readFileSync(path.join(root, 'src', 'data', 'verseCounts.json'), 'utf8'));
const booksTs = fs.readFileSync(path.join(root, 'src', 'data', 'books.ts'), 'utf8');
const books = {};
for (const m of booksTs.matchAll(/\['([1-3]?[A-Za-z]+)', '([^']+)', (\d+)\]/g)) {
  const [, osis, name, chapters] = m;
  if (counts[osis]?.length !== Number(chapters)) throw new Error(`verse counts missing for ${osis}`);
  books[osis] = [name, counts[osis]];
}
if (Object.keys(books).length !== 66) throw new Error('expected 66 books');

const src = `// Bible Atlas ESV relay: a Cloudflare Worker (generated by scripts/build-relay.mjs; do not edit by hand).
//
// The app asks this relay for a passage; the relay adds the ESV API key, which is kept as a
// Cloudflare secret named ESV_API_KEY, and asks Crossway's official ESV API. The key is never
// sent to browsers, stored in the repository or published with the website.
//
// It keeps to Crossway's free, non-commercial ESV API terms (https://api.esv.org/):
//  - at most 500 verses, and at most half of a book, per request (one screen in the app)
//  - ESV text is never cached by the relay ("Cache-Control: no-store")
//  - only requests from the app's own site are answered (ALLOWED_ORIGINS)
//
// Settings (Cloudflare dashboard → the Worker → Settings → Variables and Secrets):
//   ESV_API_KEY      secret, required: the token from api.esv.org
//   ALLOWED_ORIGINS  text, optional:   comma-separated sites allowed to use the relay
//                                      (default: https://justindrewadams.github.io)

const BOOKS = ${JSON.stringify(books)};

const DEFAULT_ORIGINS = 'https://justindrewadams.github.io';
const MAX_VERSES = 500;

function allowedOrigin(request, env) {
  const origin = request.headers.get('Origin') || '';
  const allowed = (env.ALLOWED_ORIGINS || DEFAULT_ORIGINS).split(',').map((s) => s.trim()).filter(Boolean);
  return allowed.includes(origin) ? origin : null;
}

function reply(body, status, origin) {
  return new Response(JSON.stringify(body), {
    status,
    headers: {
      'Content-Type': 'application/json; charset=utf-8',
      'Cache-Control': 'no-store',
      ...(origin ? { 'Access-Control-Allow-Origin': origin, Vary: 'Origin' } : {}),
    },
  });
}

export default {
  async fetch(request, env) {
    const origin = allowedOrigin(request, env);
    if (request.method === 'OPTIONS') {
      return new Response(null, {
        status: origin ? 204 : 403,
        headers: origin
          ? { 'Access-Control-Allow-Origin': origin, 'Access-Control-Allow-Methods': 'GET', 'Access-Control-Max-Age': '86400', Vary: 'Origin' }
          : {},
      });
    }
    if (!origin) return reply({ error: 'This relay only serves the Bible Atlas app.' }, 403, null);
    if (request.method !== 'GET') return reply({ error: 'Only GET is supported.' }, 405, origin);
    if (!env.ESV_API_KEY) return reply({ error: 'The relay has no ESV_API_KEY secret yet.' }, 503, origin);

    const url = new URL(request.url);
    if (url.pathname !== '/passage') return reply({ error: 'Not found.' }, 404, origin);
    const book = BOOKS[url.searchParams.get('book') || ''];
    const chapter = Number(url.searchParams.get('chapter'));
    const from = Number(url.searchParams.get('from'));
    const to = Number(url.searchParams.get('to'));
    if (!book || !Number.isInteger(chapter) || chapter < 1 || chapter > book[1].length) {
      return reply({ error: 'Unknown book or chapter.' }, 400, origin);
    }
    const inChapter = book[1][chapter - 1];
    const bookTotal = book[1].reduce((a, b) => a + b, 0);
    if (!Number.isInteger(from) || !Number.isInteger(to) || from < 1 || to < from || to > inChapter) {
      return reply({ error: 'Invalid verse range.' }, 400, origin);
    }
    const limit = Math.max(1, Math.min(MAX_VERSES, Math.floor(bookTotal / 2)));
    if (to - from + 1 > limit) {
      return reply({ error: 'That is more than Crossway allows on one page (' + limit + ' verses).' }, 400, origin);
    }

    const params = new URLSearchParams({
      q: book[0] + ' ' + chapter + ':' + from + '-' + to,
      'include-headings': 'false',
      'include-footnotes': 'false',
      'include-verse-numbers': 'true',
      'include-first-verse-numbers': 'true',
      'include-short-copyright': 'false',
      'include-copyright': 'false',
      'include-passage-references': 'false',
    });
    const res = await fetch('https://api.esv.org/v3/passage/text/?' + params, {
      headers: { Authorization: 'Token ' + env.ESV_API_KEY },
    });
    if (res.status === 429) return reply({ error: 'The ESV service limit was reached. Please try again later.' }, 429, origin);
    if (res.status === 401 || res.status === 403) return reply({ error: 'The relay\\'s ESV key was not accepted.' }, 502, origin);
    if (!res.ok) return reply({ error: 'The ESV service returned ' + res.status + '.' }, 502, origin);
    const data = await res.json();
    return reply({ passages: data.passages || [] }, 200, origin);
  },
};
`;
fs.mkdirSync(path.join(root, 'relay'), { recursive: true });
fs.writeFileSync(path.join(root, 'relay', 'esv-relay.js'), src);
console.log(`relay/esv-relay.js written (${(src.length / 1024).toFixed(1)} KB)`);
